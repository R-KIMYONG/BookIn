taste_read: "기분 따라 무게추를 자유롭게 옮기는, 스위치가 유연한 타입 같아요."
fun_fortune: "재미로 점쳐보면, 연애할 땐 밀당은 못 하고 좋으면 바로 티 내는 쪽일 듯요."
